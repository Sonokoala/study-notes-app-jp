"""AI への指示文。どれも JSON オブジェクトを1つだけ返すように頼む。

ノート: 日本語（専門用語は英語のまま、発音はカタカナ）
プレゼン: 英語（ノート欄の英語原稿で、話す練習にも使う）
"""
import os

_HERE = os.path.dirname(os.path.abspath(__file__))
with open(os.path.join(_HERE, "assets", "quad_example.json"), encoding="utf-8") as f:
    QUAD_EXAMPLE = f.read()

MAX_CHARS = 60000
LANG_JA = "本文は日本語で書く。専門用語・コマンド・画面の表示名は英語の原文のまま残す（教材が英語の場合も日本語の場合も同じ）。\n"


def source_block(kind, subject, text=None):
    head = f"科目: {subject or '（不明。内容から判断する）'}\n"
    if kind == "recording":
        body = (text or "")[:MAX_CHARS]
        return head + ("教材: 授業・仕事の研修（新人研修など）・チュートリアル・勉強会を録画または録音した文字起こし。説明された手順、つまずいた所、"
                       "質問と答えもすべて内容に含める。\n\n"
                       "--- 文字起こし ---\n" + body + "\n--- ここまで ---\n")
    return head + ("教材: 授業資料のスクリーンショット（添付画像。撮った順）。"
                   "画像の文字が原文なので、用語や英語の表記はそのまま使う。\n")


def topic(src):
    return src + """
この教材の主なトピックを決める。JSON だけを出力する:
{"topic": "日本語で20文字以内"}"""


def quad(src):
    return src + LANG_JA + """
この教材から4分割の学習ノートを作る。1ページ1トピック、3〜8ページ、ページ間で内容を重複させない。
読む人は、別の分野から来て、短い期間に処理しきれないほどの知識を詰め込まれている新人や学習者。
パッと見て理解できるように、1ページに載せる情報を絞り、専門外の人にも分かる言葉で書く。
各ページの4つの区画:
- diagram（左上・図解）: 24 x 12 のグリッドに箱と矢印を置き、しくみ・流れ・比較を見せる。箱は6〜14個、
  1行は全角18文字まで。style: navy（中心になるもの）/ blue / teal（良い・安全）/ pink（リスク・攻撃）/
  orange（ルール・注意）/ gray（入れ物・計算式）/ white。
- concepts（右上・キーコンセプト）: 3〜5項目、各1〜2文。「〜なら → 〇〇」の形で書く。要点・数字・結論を **太字** にする。
- terms（左下・用語と発音）: 専門用語 6〜8項目＋熟語・イディオム 2項目（合計10項目まで。枠に収めるため def と tip は短く）。
  日本の学校英語（大学まで）では習わない、その分野の専門用語を優先する。中学・高校で習う一般的な単語は選ばない。
  term = 英語の専門用語（略語なら正式名も）、def = カタカナ読み＋短い日本語の定義、
  pron = カタカナの発音。強く読む音節を **太字** にする（例: "**ア**ロケイト"）。和製英語の読みではなく本当の英語の強勢で。
  tip = 日本人がつまずきやすい点の短いコツ（l と r、th、黙字、母音の長さ、強勢の位置など）、
  warn = 混同しやすい語・和製英語の落とし穴（任意）。
  さらに、教材に出てきた、その分野や職場でよく使う熟語・イディオム・句動詞を2個、"tag": "Idiom" を付けて入れる
  （意味を取り違えやすい一般的な英単語なら "tag": "英単語"）。会議や顧客への説明でそのまま使える形にする。
- examples（右下・具体例）: 2〜4項目 {"label", "text"}。具体的な計算例・コマンド・場面の例と、
  身近なたとえ話（引っ越し、本棚、ビルなど）を混ぜる。答えや結果を **太字** にする。
各ページには title（日本語の見出し）と title_en（英語の正式な用語での見出し）を付ける。
文字としてのアスタリスクは \\\\* と書く。

この例と同じ構造の JSON オブジェクトだけを出力する（"theme": "dark" を付ける）:
""" + QUAD_EXAMPLE


def deck(src):
    return src + """
この教材から、英語を話す練習にも使うプレゼンを作る。スライドもノート欄の原稿も、すべて英語で書く（教材が日本語でも英語にする）。6〜12枚。
- title: 短い英語の見出し。bullets: 短い英語の要点を2〜4個。
- script: 声に出して読む、自然な話し言葉の英語。1要素＝1文で、一息で読める長さにする。
  文の中で強く読む語（大事な内容語）を **二重アスタリスク** で囲む。強く読む語として表示される。
  平易で分かりやすい文にする。1枚あたり3〜8文。
JSON だけを出力する:
{"title": "...", "subtitle": "...", "intro_script": ["..."], "slides": [{"title": "...", "bullets": ["..."], "script": ["..."]}]}"""
